def test_runtime_bundle_dispatch_template_token() -> None:
    assert runtime_bundle._DISPATCH_BRANCH_TOKEN in runtime_bundle._DISPATCH
    rendered_empty = runtime_bundle._DISPATCH.replace(runtime_bundle._DISPATCH_BRANCH_TOKEN, "")
    assert "__SESSION_START_BRANCH__" not in rendered_empty
    rendered_branch = runtime_bundle._DISPATCH.replace(
        runtime_bundle._DISPATCH_BRANCH_TOKEN, runtime_bundle._SESSION_START_BRANCH
    )
    assert "__SESSION_START_BRANCH__" not in rendered_branch
    assert "session_start" in rendered_branch


def test_static_templates_carry_no_orphan_tokens() -> None:
    """Templates with no placeholders at all must stay that way."""
    from chock.scaffold import agents_md, install_ci, templates

    for text in (
        install_ci.WORKFLOW_TEMPLATE,
        templates._GITATTRIBUTES_TEMPLATE,
        templates.POLICIES_GUARDRAIL,
        templates.SKILLS_GUARDRAIL,
        agents_md.POINTER_BLOCK,
        runtime_bundle._IMPORTS,
        runtime_bundle._SESSION_START_BRANCH,
        runtime_bundle._SESSION_START_ORCHESTRATION,
    ):
        assert not _TOKEN_RE.search(text), f"unexpected placeholder in static template: {text}"
