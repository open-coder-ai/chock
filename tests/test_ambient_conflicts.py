_HEADER = "<!-- GENERATED by `chock sync` -- do not edit -->\n\n# .agents/policies/INDEX.md\n\n"


def _index(rules_section: str) -> str:
    return _HEADER + "## Rules — always apply\n\n" + rules_section


def _write_index(root: Path, text: str) -> Path:
    path = root / ".agents" / "policies" / "INDEX.md"
    path.parent.mkdir(parents=True)
    path.write_text(text, encoding="utf-8")
    return path


def _run(root: Path) -> Report:
    report = Report()
    check_ambient_conflicts(root, report)
    return report


def _line_of(text: str, needle: str) -> int:
    for i, line in enumerate(text.splitlines(), start=1):
        if needle in line:
            return i
    raise AssertionError(f"{needle!r} not found")


def test_two_policies_disagreeing_produce_an_error_naming_both_sides(tmp_path: Path) -> None:
    text = _index("- **policy-a**: never(dead_code): delete\n- **policy-b**: prefer(dead_code): keep\n")
    _write_index(tmp_path, text)

    report = _run(tmp_path)

    assert not report.warnings
    assert len(report.errors) == 1
    finding = report.errors[0]
    assert finding.check == "direct_contradiction"
    assert "policy-a" in finding.message
    assert "policy-b" in finding.message
    assert f"line {_line_of(text, 'policy-a')}" in finding.message
    assert f"line {_line_of(text, 'policy-b')}" in finding.message


