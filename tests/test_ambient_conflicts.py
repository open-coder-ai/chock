def test_scope_overlap_via_nested_verb_call(tmp_path: Path) -> None:
    """`agent_config(paths): never(hand_edit)` vs a policy permitting edits to one of those paths."""
    text = _index(
        "- **protect-agent-config**: agent_config(AGENTS.md|.claude/settings): never(hand_edit)\n"
        "- **allow-settings-edits**: require_approval(.claude/settings): hand_edit\n"
    )
    _write_index(tmp_path, text)

    report = _run(tmp_path)

    assert len(report.errors) == 1
    finding = report.errors[0]
    assert finding.check == "scope_overlap"
    assert ".claude/settings" in finding.message
    assert "protect-agent-config" in finding.message
    assert "allow-settings-edits" in finding.message


def test_same_verb_with_different_targets_is_not_a_conflict(tmp_path: Path) -> None:
    """`never(commit): secrets` and `never(commit): --no-verify` both extend the same
    forbidden-target list; that is additive, not contradictory. Real chock content hits
    exactly this shape (block-no-verify and code-safety both scope `never` to `commit`)."""
    text = _index("- **policy-a**: never(commit): secrets\n- **policy-b**: never(commit): --no-verify\n")
    _write_index(tmp_path, text)

    report = _run(tmp_path)

    assert not report.errors
    assert not report.warnings


def test_reviewed_override_suppresses_exactly_that_finding(tmp_path: Path) -> None:
    text = _index(
        "- **policy-a**: never(dead_code): delete  # chock: conflict-reviewed dead_code\n"
        "- **policy-b**: prefer(dead_code): keep\n"
        "- **policy-c**: never(hook_bypass): skip\n"
        "- **policy-d**: prefer(hook_bypass): skip\n"
    )
    _write_index(tmp_path, text)

    report = _run(tmp_path)

    assert len(report.errors) == 1
    assert "hook_bypass" in report.errors[0].message
    assert "dead_code" not in report.errors[0].message


