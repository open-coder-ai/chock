def test_end_to_end_through_the_real_compiler(tmp_path: Path) -> None:
    """Two real policy manifests, compiled by the real index pipeline, still produce a finding."""

    def _write_policy(policy_id: str, rule_text: str) -> None:
        policy_dir = tmp_path / ".agents" / "policies" / policy_id
        policy_dir.mkdir(parents=True)
        data = {
            "id": policy_id,
            "name": policy_id,
            "version": "0.1.0",
            "description": f"Description for {policy_id}.",
            "artifact": "rule",
            "enforcement": "advise",
            "provenance": {"author": "x", "license": "Apache-2.0", "trust_tier": "sandbox"},
            "rule": {"text": rule_text},
        }
        (policy_dir / "manifest.yaml").write_text(yaml.safe_dump(data), encoding="utf-8")

    _write_policy("policy-a", "never(dead_code): delete")
    _write_policy("policy-b", "prefer(dead_code): keep")

    entries, _warnings = build_entries(tmp_path)
    output = render_index(entries, 2000)
    index_path = tmp_path / ".agents" / "policies" / "INDEX.md"
    index_path.parent.mkdir(parents=True, exist_ok=True)
    index_path.write_text(output.main, encoding="utf-8")

    report = _run(tmp_path)

    assert len(report.errors) == 1
    assert report.errors[0].check == "direct_contradiction"


def test_conflicts_only_flag_from_the_cli(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    text = _index("- **policy-a**: never(dead_code): delete\n- **policy-b**: prefer(dead_code): keep\n")
    _write_index(tmp_path, text)

    rc = conflicts_main(["--repo", str(tmp_path)])

    assert rc == 1
    out = capsys.readouterr().out
    assert "direct_contradiction" in out


def test_no_model_call_static_scan() -> None:
    """The design's core claim: nothing in this path can call a model."""
    for module in (checks_conflicts, ambient_parser):
        source = Path(module.__file__).read_text(encoding="utf-8").lower()
        for forbidden in ("openai", "anthropic", "requests.", "httpx", "socket.", "\\bllm\\b"):
            assert forbidden.rstrip(".") not in source, f"{module.__name__} mentions {forbidden!r}"


def test_no_model_call_network_and_subprocess_are_never_invoked(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Belt-and-suspenders: patch the only ways this process could reach a model, then run
    the check for real. If it needed a model call, one of these would raise."""

    def _boom(*_args, **_kwargs):
        raise AssertionError("check_ambient_conflicts must never touch the network or a subprocess")

    monkeypatch.setattr(urllib.request, "urlopen", _boom)
    monkeypatch.setattr(subprocess, "run", _boom)
    monkeypatch.setattr(subprocess, "Popen", _boom)

    text = _index("- **policy-a**: never(dead_code): delete\n- **policy-b**: prefer(dead_code): keep\n")
    _write_index(tmp_path, text)

    report = _run(tmp_path)
    assert len(report.errors) == 1
